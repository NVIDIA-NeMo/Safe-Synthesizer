"""Generate the common words that free-text PII replacement does not search for.

Free-text replacement searches each record or group for values it already
knows, such as a structured first name, and replaces occurrences the detector
missed. A known one-word value that is also a common English word, such as
``Will`` or ``Brown``, is left to the detector, because searching for it would
also replace the ordinary word.

The list is the overlap of two sources, adjusted by hand:

- Common English words: lowercase entries of SCOWL 2020.12.07 size 35, the size
  spell checkers use for ordinary vocabulary. Download it from
  https://sourceforge.net/projects/wordlist/files/SCOWL/2020.12.07/ and pass
  the extracted ``final`` directory. SCOWL's notice is in ``THIRD_PARTY.md``.
- Names: SCOWL's proper names, which include the 1990 US Census first and last
  names, plus Faker's ``en_US`` first and last names.

Usage:
    uv run --frozen tools/gen_common_words.py /path/to/scowl-2020.12.07/final
"""

from __future__ import annotations

import textwrap
from pathlib import Path

import click
from faker.providers.person.en_US import Provider as FakerPersonProvider

OUTPUT = Path(__file__).parents[1] / "src/nemo_safe_synthesizer/pii_replacer/replacement/common_words.py"

_SCOWL_WORD_FILES = (
    *(f"english-words.{size}" for size in (10, 20, 35)),
    *(f"american-words.{size}" for size in (10, 20, 35)),
)
_SCOWL_NAME_FILES = ("english-proper-names.35", "english-proper-names.50", "american-proper-names.50")

# Words in the overlap that text almost always uses as names, so a missed occurrence should still be searched for.
_NAMES_NOT_WORDS = frozenset(
    {
        "cooper",
        "don",
        "earl",
        "harry",
        "jay",
        "lee",
        "maria",
        "martin",
        "mike",
        "miller",
        "peter",
        "peters",
        "sally",
        "smith",
        "wright",
    }
)

# Words missing from the overlap: names that are also common words, such as months that SCOWL lists only
# capitalized, and placeholders that structured columns use for a missing value.
_EXTRA_COMMON_WORDS = frozenset(
    {
        # Names
        "april",
        "august",
        "hope",
        "june",
        # Placeholders
        "anonymous",
        "missing",
        "n/a",
        "nan",
        "none",
        "null",
        "other",
        "redacted",
        "test",
        "unknown",
    }
)

_HEADER = '''\
# SPDX-FileCopyrightText: Copyright (c) 2026 NVIDIA CORPORATION & AFFILIATES. All rights reserved.
# SPDX-License-Identifier: Apache-2.0

"""Common English words that are also names, and missing-value placeholders.

Free-text replacement does not search for a known one-word value in this list. Generated by
``tools/gen_common_words.py`` from SCOWL and Faker name lists; do not edit by hand. SCOWL's
notice is in ``THIRD_PARTY.md``.
"""

from __future__ import annotations

__all__ = ["COMMON_WORDS"]

COMMON_WORDS: frozenset[str] = frozenset(
    """
'''

_FOOTER = '''\
    """.split()
)
'''


def _read_words(directory: Path, file_names: tuple[str, ...]) -> set[str]:
    words: set[str] = set()
    for file_name in file_names:
        path = directory / file_name
        if not path.is_file():
            raise click.ClickException(f"missing SCOWL file {path}")
        words.update(line.strip() for line in path.read_text(encoding="latin-1").splitlines())
    return words


def build_common_words(scowl_final: Path) -> list[str]:
    """Return the sorted, lowercase words to write into the generated module."""
    common_words = {word for word in _read_words(scowl_final, _SCOWL_WORD_FILES) if word.isalpha() and word.islower()}
    faker_names = [*FakerPersonProvider.first_names, *FakerPersonProvider.last_names]
    names = {name.lower() for name in [*_read_words(scowl_final, _SCOWL_NAME_FILES), *faker_names] if name.isalpha()}
    return sorted(((common_words & names) - _NAMES_NOT_WORDS) | _EXTRA_COMMON_WORDS)


@click.command()
@click.argument("scowl_final", type=click.Path(exists=True, file_okay=False))
def main(scowl_final: str) -> None:
    """Write the common-word list from SCOWL_FINAL, the ``final`` directory of SCOWL 2020.12.07."""
    words = build_common_words(Path(scowl_final))
    body = textwrap.fill(" ".join(words), width=116, initial_indent="    ", subsequent_indent="    ")
    OUTPUT.write_text(f"{_HEADER}{body}\n{_FOOTER}", encoding="utf-8")
    click.echo(f"wrote {len(words)} words to {OUTPUT}")


if __name__ == "__main__":
    main()
